import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { verifyLiveBenchmark } from "../../benchmarks/verify";

const requestedPath = process.argv[2];
if (!requestedPath) throw new Error("Pass a live benchmark raw JSON file.");
const sourcePath = resolve(requestedPath);
const run = JSON.parse(readFileSync(sourcePath, "utf8")) as Record<string, any>;
const verification = verifyLiveBenchmark(run);
if (!verification.ok) {
  throw new Error(`Cannot accept live benchmark: ${verification.errors.join(" ")}`);
}

const publicRoot = resolve("public/benchmarks", String(run.run_id));
mkdirSync(publicRoot, { recursive: true });
const sanitized = {
  ...run,
  trials: run.trials.map(
    ({ checkpoint_id: _checkpointId, ...trial }: Record<string, unknown>) =>
      trial,
  ),
};
const rawSource = `${JSON.stringify(sanitized, null, 2)}\n`;
writeFileSync(resolve(publicRoot, "raw.json"), rawSource);

const lanes = run.summary["live-service"];
const webP50 = lanes.webmcp.warm.task_duration_ms.p50.value;
const officialP50 = lanes["official-mcp"].warm.task_duration_ms.p50.value;
const webP90 = lanes.webmcp.warm.task_duration_ms.p90.value;
const officialP90 = lanes["official-mcp"].warm.task_duration_ms.p90.value;
const summary = {
  schema_version: 1,
  run_id: run.run_id,
  recorded_at: run.recorded_at,
  evidence_class: "live-production-task-boundary",
  comparable_as_prompt_to_visible: false,
  claim_scope:
    "Observed production task speedup. WebMCP includes two page calls and a rendered canvas change; official MCP ends at checkpoint response before widget rendering.",
  boundary_note: run.method.comparability,
  environment: run.environment,
  method: run.method,
  scenario: run.scenario,
  counts: {
    total_trials: run.trials.length,
    pairs: run.method.warm_pairs,
    semantic_successes: run.trials.filter(
      (trial: Record<string, unknown>) => trial.semantic_pass === true,
    ).length,
    rendered_webmcp_successes: run.trials.filter(
      (trial: Record<string, unknown>) =>
        trial.lane === "webmcp" && trial.visual_change_detected === true,
    ).length,
  },
  comparison: {
    p50: {
      webmcp_ms: webP50,
      official_mcp_ms: officialP50,
      webmcp_speedup: officialP50 / webP50,
    },
    p90: {
      webmcp_ms: webP90,
      official_mcp_ms: officialP90,
      webmcp_speedup: officialP90 / webP90,
    },
  },
  lanes,
  raw: {
    path: `/benchmarks/${run.run_id}/raw.json`,
    sha256: createHash("sha256").update(rawSource).digest("hex"),
    bytes: Buffer.byteLength(rawSource),
  },
};
const summarySource = `${JSON.stringify(summary, null, 2)}\n`;
writeFileSync(resolve(publicRoot, "summary.json"), summarySource);
writeFileSync(resolve("public/benchmarks/live-latest.json"), summarySource);
writeFileSync(
  resolve("src/data/live-benchmark-evidence.ts"),
  `// Generated by scripts/benchmarks/accept-live-run.ts.\nexport const liveBenchmarkEvidence = ${JSON.stringify(summary, null, 2)} as const;\n`,
);
console.log(`Accepted live benchmark evidence: ${publicRoot}`);
