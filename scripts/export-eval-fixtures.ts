import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { TOOL_DEFINITIONS, TOOL_NAMES } from "../src/webmcp/tool-contracts";

const outputPath = resolve("evals/tools.json");
mkdirSync(dirname(outputPath), { recursive: true });
const tools = TOOL_NAMES.map((name) => ({
  name,
  description: TOOL_DEFINITIONS[name].description,
  inputSchema: TOOL_DEFINITIONS[name].inputSchema,
}));
writeFileSync(outputPath, `${JSON.stringify({ tools }, null, 2)}\n`);
const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  code: { source: true, esm: true },
});
for (const name of TOOL_NAMES) {
  ajv.addSchema(TOOL_DEFINITIONS[name].inputSchema, name);
}
const compiled = Object.fromEntries(TOOL_NAMES.map((name) => [name, name]));
const validatorPath = resolve("src/webmcp/generated-validators.ts");
const standaloneSource = standaloneCode(ajv, compiled);
const runtimeHelper =
  'const func1 = require("ajv/dist/runtime/ucs2length").default;';
if (!standaloneSource.includes(runtimeHelper)) {
  throw new Error("The generated validator runtime helper changed unexpectedly.");
}
const validatorSource =
  "const func1 = (value) => Array.from(value).length;\n" +
  standaloneSource.replace(runtimeHelper, "");
if (validatorSource.includes("require(")) {
  throw new Error("Standalone validators still contain CommonJS runtime imports.");
}
writeFileSync(
  validatorPath,
  `/* Generated by scripts/export-eval-fixtures.ts. Do not edit. */\n/* oxlint-disable */\n// @ts-nocheck\n${validatorSource}\n`,
);
console.log(`Wrote ${tools.length} WebMCP tool schemas to ${outputPath}`);
console.log(`Wrote standalone validators to ${validatorPath}`);
